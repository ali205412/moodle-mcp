/**
 * Install hook: tokens are hashed from the start, and the signing secret exists before any request.
 *
 * @return bool
 */
function xmldb_webservice_mcp_install(): bool {
    set_config('tokenshashed', 1, 'webservice_mcp');
    webservice_mcp_ensure_signing_secret();
    return true;
}
